package llamaswap

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// SetModel adds or replaces one model entry under models.<slug>, leaving every
// other part of the file — comments, other models, groups — as it was.
func (m *Manager) SetModel(slug string, model ModelConfig) error {
	text, err := m.ConfigYAML()
	if err != nil {
		return err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal([]byte(text), &doc); err != nil {
		return fmt.Errorf("parse config: %w", err)
	}
	if len(doc.Content) == 0 {
		return fmt.Errorf("config is empty")
	}
	root := doc.Content[0]

	modelsNode := findKey(root, "models")
	if modelsNode == nil {
		modelsNode = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		root.Content = append(root.Content, strNode("models"), modelsNode)
	}

	entry := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	addString(entry, "name", model.Name)
	addString(entry, "description", model.Description)
	addString(entry, "proxy", model.Proxy)
	addString(entry, "cmd", model.Cmd)
	addString(entry, "cmdStop", model.CmdStop)
	addString(entry, "checkEndpoint", model.CheckEndpoint)
	entry.Content = append(entry.Content, strNode("ttl"),
		&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: strconv.Itoa(model.TTL)})

	replaced := false
	for i := 0; i+1 < len(modelsNode.Content); i += 2 {
		if modelsNode.Content[i].Value == slug {
			modelsNode.Content[i+1] = entry
			replaced = true
			break
		}
	}
	if !replaced {
		modelsNode.Content = append(modelsNode.Content, strNode(slug), entry)
	}

	out, err := yaml.Marshal(&doc)
	if err != nil {
		return err
	}
	return m.SaveConfigYAML(string(out))
}

// FindModel reports one model entry from the managed config.
func (m *Manager) FindModel(slug string) (ModelConfig, bool) {
	cfg, err := m.Config()
	if err != nil {
		return ModelConfig{}, false
	}
	model, ok := cfg.Models[slug]
	return model, ok
}

// RecipeModel is the llama-swap entry generated for a Hub recipe: the sidecar
// starts the recipe through the Hub on demand and holds the request there
// until the model answers, then stops it when llama-swap swaps it out. The
// two scripts keep the credentials out of the YAML and out of the shell
// quoting rules.
func (m *Manager) RecipeModel(slug, name, description string, port, hubPort int, token string) (ModelConfig, error) {
	binDir := filepath.Join(m.Home, "bin")
	if err := os.MkdirAll(binDir, 0o755); err != nil {
		return ModelConfig{}, err
	}
	base := fmt.Sprintf("http://127.0.0.1:%d/api/recipes/%s", hubPort, slug)
	cookie := fmt.Sprintf(`Cookie: spark_ai_hub_session=%s`, token)

	start := filepath.Join(binDir, "hub-"+slug+".sh")
	stop := filepath.Join(binDir, "hub-"+slug+"-stop.sh")
	runDir := filepath.Join(m.Home, "run")
	if err := os.MkdirAll(runDir, 0o755); err != nil {
		return ModelConfig{}, err
	}
	pidFile := filepath.Join(runDir, slug+".pid")
	startBody := strings.Join([]string{
		"#!/bin/sh",
		"# Generated by gospark-hub: start the recipe, then hold the process so",
		"# llama-swap keeps waiting on checkEndpoint until the model answers.",
		"# 409 means the recipe is already up, which is success here.",
		`code=$(curl -s -o /dev/null -w '%{http_code}' -X POST -H '` + cookie + `' ` + base + `/launch)`,
		`case "$code" in 200|409) ;; *) echo "hub launch <` + slug + `> answered $code" >&2; exit 1 ;; esac`,
		`echo $$ > '` + pidFile + `'`,
		"exec sleep infinity",
		"",
	}, "\n")
	stopBody := strings.Join([]string{
		"#!/bin/sh",
		"# Generated by gospark-hub: stop the recipe and release the holder, or",
		"# llama-swap waits forever for this model's process to exit.",
		"# Only stop when OUR holder is alive. A late stop from a model that",
		"# llama-swap already unloaded must not kill a recipe the user started",
		"# from the Hub in the meantime — that launch has no pid file.",
		`pid=$(cat '` + pidFile + `' 2>/dev/null)`,
		`if [ -z "$pid" ] || ! kill -0 "$pid" 2>/dev/null; then exit 0; fi`,
		`curl -s -o /dev/null -X POST -H '` + cookie + `' ` + base + `/stop`,
		`kill "$pid" 2>/dev/null`,
		`rm -f '` + pidFile + `'`,
		"",
	}, "\n")
	if err := os.WriteFile(start, []byte(startBody), 0o700); err != nil {
		return ModelConfig{}, err
	}
	if err := os.WriteFile(stop, []byte(stopBody), 0o700); err != nil {
		return ModelConfig{}, err
	}

	return ModelConfig{
		Name:          name,
		Description:   description,
		Proxy:         fmt.Sprintf("http://127.0.0.1:%d", port),
		Cmd:           start,
		CmdStop:       stop,
		CheckEndpoint: "/v1/models",
		// ttl 0: llama-swap keeps it warm; the group decides eviction.
		TTL: 0,
	}, nil
}

func strNode(value string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: value}
}

func addString(node *yaml.Node, key, value string) {
	if value == "" {
		return
	}
	node.Content = append(node.Content, strNode(key), strNode(value))
}

func findKey(mapping *yaml.Node, key string) *yaml.Node {
	if mapping == nil || mapping.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(mapping.Content); i += 2 {
		if mapping.Content[i].Value == key {
			return mapping.Content[i+1]
		}
	}
	return nil
}
