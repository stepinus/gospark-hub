package proxy

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gospark-hub/internal/config"
	"gospark-hub/internal/registry"
)

// Render builds the whole front-door config from the recipe registry.
//
// The output is deliberately byte-for-byte what upstream's
// proxy_service.render_caddyfile produces (after normalising the probe token
// and the two ports): the ordering probe → 308 redirect → guarded block is
// load-bearing, and testdata/upstream.Caddyfile pins it.
func Render(cfg config.Config, recipes []registry.Recipe) string {
	token := probeToken(cfg)
	daemon := fmt.Sprintf("host.docker.internal:%d", cfg.Port)

	lines := []string{
		"# Generated by Spark AI Hub — edits here are overwritten on restart.",
		"{",
		"\tadmin 0.0.0.0:2019",
		"\tauto_https off",
		// Without this, Caddy rewrites X-Forwarded-Proto to the scheme *it*
		// was spoken to — always plain http — and the daemon behind it can
		// never tell that the user arrived over https. That is how the Hub
		// ends up printing http:// links for an https tunnel and setting a
		// session cookie without Secure. cloudflared/nginx/ngrok all sit on
		// a private address, so trust the forwarded headers from there and
		// let the real client's scheme and hostname through.
		"\tservers {",
		"\t\ttrusted_proxies static private_ranges",
		"\t}",
		"}",
		"",
		fmt.Sprintf(":%d {", cfg.PublicPort),
	}

	for _, recipe := range proxiedRecipes(recipes) {
		slug := recipe.Slug
		upstream := fmt.Sprintf("%s:%d", containerName(cfg, slug), recipe.UI.Port)
		if recipe.IsNative() {
			// A native recipe has no container to dial: it listens on the host,
			// which Caddy reaches through the host-gateway alias it already has.
			port := recipe.UI.Port
			if recipe.Native != nil && recipe.Native.Port != 0 {
				port = recipe.Native.Port
			}
			upstream = fmt.Sprintf("host.docker.internal:%d", port)
		}
		lines = append(lines, "\t# "+slug)
		// The daemon's own health probe, before the guarded route so it wins.
		lines = append(lines,
			"\t@probe-"+slug+" {",
			fmt.Sprintf("\t\tpath %s/%s/*", AppPrefix, slug),
			fmt.Sprintf("\t\theader %s %q", ProbeHeader, token),
			"\t}",
			"\thandle @probe-"+slug+" {",
		)
		if recipe.UI.StripPrefix {
			lines = append(lines, fmt.Sprintf("\t\turi strip_prefix %s/%s", AppPrefix, slug))
		}
		lines = append(lines,
			"\t\treverse_proxy "+upstream,
			"\t}",
		)
		// handle_path only matches the trailing-slash form, so send the bare
		// /run/{slug} there first or the first click 404s.
		lines = append(lines, fmt.Sprintf("\tredir %s/%s %s/%s/ 308", AppPrefix, slug, AppPrefix, slug))
		// handle_path strips the prefix; handle leaves it on for the apps that
		// want to see it (FastAPI root_path).
		directive := "handle"
		if recipe.UI.StripPrefix {
			directive = "handle_path"
		}
		lines = append(lines, fmt.Sprintf("\t%s %s/%s/* {", directive, AppPrefix, slug))
		if cfg.AuthEnabled {
			// The apps have no accounts of their own. ComfyUI or a Gradio file
			// box on a public tunnel is an open GPU, so the Hub's own session
			// gates them: /api/auth/me answers 200 signed-in, 401 otherwise.
			lines = append(lines,
				"\t\tforward_auth "+daemon+" {",
				"\t\t\turi /api/auth/me",
				"\t\t\t@denied status 401 403",
				"\t\t\thandle_response @denied {",
				"\t\t\t\tredir * / 302",
				"\t\t\t}",
				"\t\t}",
			)
		}
		lines = append(lines,
			"\t\treverse_proxy "+upstream,
			"\t}",
			"",
		)
	}

	lines = append(lines,
		"\t# Everything else is the Hub itself.",
		"\thandle {",
		"\t\treverse_proxy "+daemon,
		"\t}",
		"}",
		"",
	)
	return strings.Join(lines, "\n")
}

// proxiedRecipes is upstream's _proxied_recipes filter: ui.proxy == true and
// ui.type in ("web", "api-only"). An API-only recipe can be proxied too (image
// servers the MCP tools call): it gets the route and health probe, just no
// Open button. Sorted by slug so the output is deterministic even if the
// caller's slice is not.
func proxiedRecipes(recipes []registry.Recipe) []registry.Recipe {
	out := make([]registry.Recipe, 0, len(recipes))
	for _, recipe := range recipes {
		if !recipe.UI.Proxy {
			continue
		}
		if recipe.UI.Type != "web" && recipe.UI.Type != "api-only" {
			continue
		}
		out = append(out, recipe)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Slug < out[j].Slug })
	return out
}

// containerName is the name Caddy dials, read off the recipe's own compose
// file. Not derived from the slug: four recipes name their container for the
// app rather than the recipe (facefusion-spark -> spark-ai-hub-facefusion,
// trellis2-spark -> spark-ai-hub-trellis2, and so on), and guessing would
// route those to a host that does not exist.
//
// The fallback is prefixed with cfg.Project so a second Hub cannot collide;
// an explicit container_name is used verbatim because that is what compose
// actually creates.
func containerName(cfg config.Config, slug string) string {
	compose := filepath.Join(cfg.RegistryPath, slug, "docker-compose.yml")
	if data, err := os.ReadFile(compose); err == nil {
		for line := range strings.SplitSeq(string(data), "\n") {
			if after, ok := strings.CutPrefix(line, "    container_name:"); ok {
				name := strings.TrimSpace(after)
				if name != "" {
					return name
				}
			}
		}
	}
	return cfg.Project + "-" + slug
}
